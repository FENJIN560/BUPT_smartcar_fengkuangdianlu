#ifndef _IMU_H_
#define _IMU_H_

#include "zf_common_typedef.h"

// ================================================================
// IMU 姿态角全局变量（单位：度）
// pitch: 俯仰角（绕X轴），roll: 横滚角（绕Y轴），yaw: 偏航角（绕Z轴，仅陀螺仪积分，存在漂移）
// ================================================================
extern volatile float imu_pitch;   // 俯仰角 °
extern volatile float imu_roll;    // 横滚角 °
extern volatile float imu_yaw;     // 偏航角 °（陀螺仪积分，长期漂移）

// ================================================================
// 接口函数
// ================================================================
uint8 imu_init(void);              // 初始化 IMU660RX，返回0成功，1失败
void  imu_update(void);            // 手动调用一次姿态解算（供主循环使用，若已用PIT则无需调用）

#endif /* _IMU_H_ */
